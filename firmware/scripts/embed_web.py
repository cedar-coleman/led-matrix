"""PlatformIO pre-build script: gzip ../web/ into src/net/web_assets.gen.cpp.

The console is compiled into the app image (not uploaded to LittleFS), so a firmware
update replaces the UI and the API together and they can never disagree. The file is
rewritten only when its contents change, so an unchanged console doesn't force a rebuild.

ETag: a hash over every file's path and bytes. ui_version: UI_VERSION from
mock_server.py (the one place the console's version is written) plus that hash.
"""
import gzip
import hashlib
import os
import re

Import("env")  # noqa: F821  (SCons injects it)

PROJECT = env["PROJECT_DIR"]  # noqa: F821
WEB = os.path.normpath(os.path.join(PROJECT, "..", "web"))
MOCK = os.path.normpath(os.path.join(PROJECT, "..", "mock_server.py"))
OUT = os.path.join(PROJECT, "src", "net", "web_assets.gen.cpp")

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".gif": "image/gif",
    ".ico": "image/x-icon",
    ".md": "text/plain; charset=utf-8",
    ".woff2": "font/woff2",
}


def collect():
    files = []
    for root, dirs, names in os.walk(WEB):
        dirs.sort()
        for n in sorted(names):
            if n.startswith("."):
                continue
            full = os.path.join(root, n)
            rel = "/" + os.path.relpath(full, WEB).replace(os.sep, "/")
            with open(full, "rb") as f:
                files.append((rel, f.read()))
    return files


def ui_base():
    try:
        with open(MOCK, encoding="utf-8") as f:
            m = re.search(r'^UI_VERSION\s*=\s*"([^"]+)"', f.read(), re.M)
            return m.group(1) if m else "0.0.0"
    except OSError:
        return "0.0.0"


def render(files):
    digest = hashlib.sha256()
    for rel, data in files:
        digest.update(rel.encode() + b"\0" + data + b"\0")
    tag = digest.hexdigest()[:16]
    out = [
        "// Generated by scripts/embed_web.py from ../web/. Do not edit.",
        '#include "web_assets.h"',
        "",
        "namespace wall {",
        "namespace net {",
        "",
    ]
    entries = []
    for i, (rel, data) in enumerate(files):
        gz = gzip.compress(data, compresslevel=9, mtime=0)
        ext = os.path.splitext(rel)[1].lower()
        out.append(f"// {rel}: {len(data)} bytes, {len(gz)} gzipped")
        out.append(f"static const uint8_t f{i}[{len(gz)}] = {{")
        for at in range(0, len(gz), 24):
            out.append("  " + ",".join(str(b) for b in gz[at:at + 24]) + ",")
        out.append("};")
        entries.append(f'  {{"{rel}", "{TYPES.get(ext, "application/octet-stream")}", f{i}, sizeof f{i}}},')
    out += ["", "const WebAsset kWebAssets[] = {"] + entries + ["};"]
    out.append(f"const size_t kWebAssetCount = {len(files)};")
    out.append(f'const char* const kWebEtag = "\\"{tag}\\"";')
    out.append(f'const char* const kUiVersion = "{ui_base()}+{tag[:8]}";')
    out += ["", "}  // namespace net", "}  // namespace wall", ""]
    return "\n".join(out)


def main():
    text = render(collect())
    try:
        with open(OUT, encoding="utf-8") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"embed_web: wrote {os.path.relpath(OUT, PROJECT)}")


main()
